// Offline invariants for railway.ts — `npm run check`, run locally and in CI.
//
// `railway config plan` needs a Railway token and a live project, so without this nothing in CI
// would ever evaluate the IaC file. This builds the same resource graph the CLI does and fails on
// the mistakes that would otherwise surface only as a broken (or non-compliant) production deploy:
//
//   1. a service, database or volume placed outside the EU region — the point of this deployment;
//   2. a secret's value written into the file instead of preserve();
//   3. the build-time and runtime backend URLs wired the wrong way round (CLAUDE.md's one gotcha);
//   4. a PORT that disagrees with the Dockerfile's EXPOSE, which Railway reports as a failed
//      healthcheck with no hint why.
//
// The region is spelled out here on purpose rather than imported from railway.ts: a check that
// read the constant it guards would pass whatever the constant said.

import { readFileSync } from "node:fs";
import { createRailwayContext, project, type ResourceNode, type VariableValue } from "railway/iac";
import program from "./railway.ts";

const REQUIRED_REGION = "europe-west4-drams3a"; // EU West, Amsterdam
const REQUIRED_BUCKET_REGION = "ams";
// Matched on the END of the name: ACCESS_TOKEN_EXPIRE_MINUTES is config, ANTHROPIC_API_KEY is not.
const SECRET_NAME = /(^|_)(SECRET|SECRET_KEY|PASSWORD|TOKEN|API_KEY|PRIVATE_KEY)$/;
const REFERENCE = /\$\{\{[^}]+\}\}/g;

const failures: string[] = [];
const fail = (message: string) => failures.push(message);

function literal(value: VariableValue | undefined): string | undefined {
  if (value?.type === "literal") return value.value ?? undefined;
  if (value?.type === "raw") return value.value.value ?? undefined;
  return undefined;
}

function exposedPort(rootDirectory: string): string | undefined {
  const dockerfile = readFileSync(new URL(`../${rootDirectory}/Dockerfile`, import.meta.url), "utf8");
  return dockerfile.match(/^EXPOSE\s+(\d+)/m)?.[1];
}

function checkRegion(resource: ResourceNode): void {
  if (resource.type === "service" || resource.type === "database") {
    const regions = Object.keys(resource.deploy?.multiRegionConfig ?? {});
    if (regions.length !== 1 || regions[0] !== REQUIRED_REGION) {
      fail(
        `${resource.address} runs in [${regions.join(", ") || "Railway's default region"}]; ` +
          `every service and database must be pinned to exactly ${REQUIRED_REGION}`,
      );
    }
  } else if (resource.type === "volume" && resource.config?.region !== REQUIRED_REGION) {
    fail(`${resource.address} is in ${resource.config?.region ?? "an unpinned region"}, not ${REQUIRED_REGION}`);
  } else if (resource.type === "bucket" && resource.config?.region !== REQUIRED_BUCKET_REGION) {
    fail(`${resource.address} is in ${resource.config?.region ?? "an unpinned region"}, not ${REQUIRED_BUCKET_REGION}`);
  }
}

function checkSecrets(resource: ResourceNode): void {
  if (resource.type !== "service" && resource.type !== "database") return;
  for (const [key, value] of Object.entries(resource.variables ?? {})) {
    if (!SECRET_NAME.test(key)) continue;
    if (value.type === "preserve" || value.type === "reference" || value.type === "sharedReference") continue;
    if (value.type === "raw" && value.value.generator) continue; // generated by Railway, never in the file
    const text = literal(value);
    if (text !== undefined && text.replace(REFERENCE, "") === "") continue; // nothing but references
    fail(`${resource.address} sets ${key} to a literal value; secrets must be preserve() and set out-of-band`);
  }
}

function checkPort(resource: ResourceNode): void {
  if (resource.type !== "service" || resource.build?.builder !== "DOCKERFILE") return;
  const rootDirectory = resource.source?.rootDirectory;
  if (!rootDirectory) return;
  const exposed = exposedPort(rootDirectory);
  const port = literal(resource.variables?.PORT);
  if (port !== exposed) {
    fail(`${resource.address} sets PORT=${port} but ${rootDirectory}/Dockerfile EXPOSEs ${exposed}`);
  }
  if (!resource.deploy?.healthcheckPath) {
    fail(`${resource.address} has no healthcheck, so a deploy that never starts would still go live`);
  }
}

function checkBackendUrls(resources: ResourceNode[]): void {
  const byName = new Map(resources.map((resource) => [resource.name, resource]));
  const frontend = byName.get("frontend");
  const backend = byName.get("backend");
  if (frontend?.type !== "service" || backend?.type !== "service") {
    fail("expected services named 'frontend' and 'backend'");
    return;
  }

  const publicUrl = literal(frontend.variables?.NEXT_PUBLIC_API_URL) ?? "";
  if (!publicUrl.startsWith("https://") || /RAILWAY_PRIVATE_DOMAIN|\.railway\.internal/.test(publicUrl)) {
    fail(
      `frontend NEXT_PUBLIC_API_URL=${publicUrl} — it is inlined into the browser bundle, so it must be ` +
        "the backend's public https:// domain, never the private network",
    );
  }

  const serverUrl = literal(frontend.variables?.BACKEND_URL) ?? "";
  if (!/\$\{\{backend\.RAILWAY_PRIVATE_DOMAIN\}\}/.test(serverUrl)) {
    fail(
      `frontend BACKEND_URL=${serverUrl} — the server-side auth proxy should reach the backend over ` +
        "the private network (${{backend.RAILWAY_PRIVATE_DOMAIN}})",
    );
  }

  const origins = (literal(backend.variables?.CORS_ORIGINS) ?? "").split(",").filter(Boolean);
  if (origins.length === 0 || !origins.every((origin) => origin.startsWith("https://"))) {
    fail(`backend CORS_ORIGINS=${origins.join(",")} — every origin must be an https:// frontend URL`);
  }
}

const definition = await program(createRailwayContext({ environment: "production" }), project);
const resources = (definition.resources ?? []).flat();

for (const resource of resources) {
  checkRegion(resource);
  checkSecrets(resource);
  checkPort(resource);
}
checkBackendUrls(resources);

if (failures.length > 0) {
  console.error(`railway.ts violates ${failures.length} deployment invariant(s):`);
  for (const message of failures) console.error(`  ✗ ${message}`);
  process.exit(1);
}
console.log(`railway.ts OK — project "${definition.name}", all resources in ${REQUIRED_REGION}:`);
for (const resource of resources) console.log(`  ✓ ${resource.address}`);
